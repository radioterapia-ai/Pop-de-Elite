CLASSIFICACOES = ("publico", "interno", "restrito", "confidencial")


def idioma_valido(idioma):
    """Normaliza 'pt-BR', 'en_US', 'Español'... para pt/en/es (padrão pt)."""
    i = str(idioma or "").strip().lower()[:2]
    return i if i in IDIOMAS else "pt"


def rotulos(idioma):
    return ROTULOS[idioma_valido(idioma)]


def tipo_doc(tipo, idioma):
    """(título do cabeçalho, 'este documento') para o tipo documental."""
    tabela = TIPOS[idioma_valido(idioma)]
    return tabela.get(str(tipo or "POP").upper(), tabela["POP"])
